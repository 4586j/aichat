// Calibrate the original and action artwork in one camera. No pixels are redrawn.
// Use the same development-only sharp installation as build-pet-actions.mjs.
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import { writeFile } from 'node:fs/promises';
const sharp=createRequire(import.meta.url)(process.env.SHARP_MODULE_PATH || 'sharp');
const size=384, output={};
const asset=name=>fileURLToPath(new URL(`../public/assets/pets/${name}`,import.meta.url));
function bounds(data){
  let left=size,right=-1,top=size,bottom=-1;
  for(let y=0;y<size;y++)for(let x=0;x<size;x++)if(data[(y*size+x)*4+3]>32){left=Math.min(left,x);right=Math.max(right,x);top=Math.min(top,y);bottom=Math.max(bottom,y);}
  if(right<left)throw new Error('Empty pet frame');
  return {left,right,top,bottom,width:right-left+1,height:bottom-top+1,cx:(left+right)/2};
}
const round=n=>Math.round(n*1e6)/1e6;
for(const id of ['cream-cat','shiba','lop-rabbit','little-fox']){
  const original=bounds(await sharp(asset(id+'-v1.png')).resize(size,size).ensureAlpha().raw().toBuffer());
  const anchor={x:original.cx,y:original.bottom},origin={x:size*.04+anchor.x*.92,y:size*.03+anchor.y*.92};
  const rows=[],all=[];
  for(let row=0;row<4;row++){
    const frames=[];
    for(let col=0;col<6;col++)frames.push(bounds(await sharp(asset(id+'-actions-v3.webp')).extract({left:col*size,top:row*size,width:size,height:size}).ensureAlpha().raw().toBuffer()));
    const a=frames[0],b=frames[5];
    // Use the same resting pose as the reference; never normalize a crouch or airborne frame independently.
    const scale=Math.sqrt(original.height/((a.height+b.height)/2)*original.width/((a.width+b.width)/2));
    const x=anchor.x-(a.cx+b.cx)/2*scale,y=anchor.y-(a.bottom+b.bottom)/2*scale;
    rows.push({scale:round(scale),x:round(x),y:round(y)});
    for(const frame of frames)all.push({left:x+frame.left*scale,right:x+frame.right*scale,top:y+frame.top*scale,bottom:y+frame.bottom*scale});
  }
  let camera=.92;
  // Keep guard space for the authored silhouette plus breathing, rotation and texture filtering.
  for(const box of [original,...all]){
    if(box.left<anchor.x)camera=Math.min(camera,(origin.x-16)/(anchor.x-box.left));
    if(box.right>anchor.x)camera=Math.min(camera,(size-16-origin.x)/(box.right-anchor.x));
    if(box.top<anchor.y)camera=Math.min(camera,(origin.y-16)/(anchor.y-box.top));
    if(box.bottom>anchor.y)camera=Math.min(camera,(size-16-origin.y)/(box.bottom-anchor.y));
  }
  output[id]={anchor,origin,camera:round(camera),bleed:round(.92/camera),rows};
}
const source='// Generated by scripts/build-pet-framing.mjs from the unchanged v1/v3 artwork.\nexport const PET_FRAMING = '+JSON.stringify(output,null,2)+';\n';
await writeFile(new URL('../public/pet-framing.js',import.meta.url),source);
