// Development-only packing and registration of imagegen's authored 24-pose actions.
// node scripts/build-pet-inbetweens.mjs <pet-id> <wave|stretch|feed|play> <6x4-source.png>
// node scripts/build-pet-inbetweens.mjs --framing | --preview
import { createRequire } from 'node:module';
import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
const { createCanvas, loadImage } = createRequire(import.meta.url)(process.env.CANVAS_MODULE_PATH || '@napi-rs/canvas');
const pets=['cream-cat','shiba','lop-rabbit','little-fox'], actions=['wave','stretch','feed','play'];
const size=384, packedSize=256, columns=6, frames=24;
const path=name=>fileURLToPath(new URL('../'+name,import.meta.url));
const asset=(id,action)=>path(`public/assets/pets/${id}-${action}-v4.webp`);
const canvas=(w=size,h=w)=>createCanvas(w,h);
function bounds(frame){
  const data=frame.getContext('2d').getImageData(0,0,frame.width,frame.height).data;
  let left=frame.width,right=-1,top=frame.height,bottom=-1;
  for(let y=0;y<frame.height;y++)for(let x=0;x<frame.width;x++)if(data[(y*frame.width+x)*4+3]>32){left=Math.min(left,x);right=Math.max(right,x);top=Math.min(top,y);bottom=Math.max(bottom,y);}
  if(right<left)throw new Error('Empty animation pose');
  return {left,right,top,bottom,width:right-left+1,height:bottom-top+1,cx:(left+right)/2};
}
function extract(image,index,cell,output=cell){
  const frame=canvas(output),ctx=frame.getContext('2d');
  ctx.drawImage(image,index%columns*cell,Math.floor(index/columns)*cell,cell,cell,0,0,output,output);
  return frame;
}
function isolate(frame){
  const ctx=frame.getContext('2d'),image=ctx.getImageData(0,0,frame.width,frame.height),data=image.data,n=frame.width;
  const visited=new Uint8Array(n*n),queue=new Int32Array(n*n);let largest=[];
  for(let start=0;start<visited.length;start++){
    if(visited[start]||data[start*4+3]<=32)continue;
    let head=0,tail=1;queue[0]=start;visited[start]=1;
    while(head<tail){const p=queue[head++],x=p%n,y=Math.floor(p/n);
      for(let dy=-1;dy<=1;dy++)for(let dx=-1;dx<=1;dx++){
        const xx=x+dx,yy=y+dy;if(xx<0||xx>=n||yy<0||yy>=n)continue;
        const next=yy*n+xx;if(!visited[next]&&data[next*4+3]>32){visited[next]=1;queue[tail++]=next;}
      }
    }
    if(tail>largest.length)largest=Array.from(queue.subarray(0,tail));
  }
  const keep=new Uint8Array(n*n);
  for(const p of largest){const x=p%n,y=Math.floor(p/n);for(let dy=-2;dy<=2;dy++)for(let dx=-2;dx<=2;dx++){const xx=x+dx,yy=y+dy;if(xx>=0&&xx<n&&yy>=0&&yy<n)keep[yy*n+xx]=1;}}
  for(let p=0;p<keep.length;p++)if(!keep[p])data[p*4+3]=0;
  ctx.putImageData(image,0,0);return frame;
}
const [id,action,source]=process.argv.slice(2);
if(id==='--framing'){
  const result={...(await import('../public/pet-framing.js')).PET_FRAMING},round=n=>Math.round(n*1e6)/1e6;
  for(const pet of pets.includes(action)?[action]:pets){
    const portrait=canvas(),image=await loadImage(path(`public/assets/pets/${pet}-v1.png`));portrait.getContext('2d').drawImage(image,0,0,size,size);
    const original=bounds(portrait),anchor={x:original.cx,y:original.bottom},origin={x:size*.04+anchor.x*.92,y:size*.03+anchor.y*.92};
    const rows=[],all=[];
    for(const kind of actions){
      const sheet=await loadImage(asset(pet,kind)),boxes=Array.from({length:frames},(_,i)=>bounds(extract(sheet,i,packedSize,size)));
      const a=boxes[0],b=boxes.at(-1),scale=Math.sqrt(original.height/((a.height+b.height)/2)*original.width/((a.width+b.width)/2));
      const x=anchor.x-(a.cx+b.cx)/2*scale,y=anchor.y-(a.bottom+b.bottom)/2*scale;
      rows.push({scale:round(scale),x:round(x),y:round(y)});
      for(const box of boxes)all.push({left:x+box.left*scale,right:x+box.right*scale,top:y+box.top*scale,bottom:y+box.bottom*scale});
    }
    let camera=.92;
    for(const box of [original,...all]){
      if(box.left<anchor.x)camera=Math.min(camera,(origin.x-16)/(anchor.x-box.left));
      if(box.right>anchor.x)camera=Math.min(camera,(size-16-origin.x)/(box.right-anchor.x));
      if(box.top<anchor.y)camera=Math.min(camera,(origin.y-16)/(anchor.y-box.top));
      if(box.bottom>anchor.y)camera=Math.min(camera,(size-16-origin.y)/(box.bottom-anchor.y));
    }
    result[pet]={anchor,origin,camera:round(camera),bleed:round(.92/camera),rows};
  }
  await writeFile(path('public/pet-framing.js'),'// Generated by scripts/build-pet-inbetweens.mjs from v1 portraits and v4 action artwork.\nexport const PET_FRAMING = '+JSON.stringify(result,null,2)+';\n');
  console.log(`Registered ${pets.includes(action)?4:16} actions in one camera per pet.`);
}else if(id==='--preview'){
  const preview=canvas(960,960),ctx=preview.getContext('2d');ctx.fillStyle='#edf2e7';ctx.fillRect(0,0,960,960);
  for(let row=0;row<pets.length;row++)for(let col=0;col<actions.length;col++)ctx.drawImage(extract(await loadImage(asset(pets[row],actions[col])),12,packedSize),col*240,row*240,240,240);
  await writeFile(path('docs/assets/pet-actions-v4.webp'),await preview.encode('webp',90));
}else{
  if(!pets.includes(id)||!actions.includes(action)||!source)throw new Error('Expected <pet-id> <action> <6x4-source.png>');
  const sheet=await loadImage(source),cell=sheet.width/columns;
  if(!Number.isInteger(cell)||sheet.height!==cell*4)throw new Error('Expected a regular 6x4 transparent sprite sheet');
  const originals=await loadImage(path(`public/assets/pets/${id}-actions-v3.webp`)),row=actions.indexOf(action);
  const first=extract(originals,row*6,size),last=extract(originals,row*6+5,size),a=bounds(first),b=bounds(last);
  const target={height:(a.height+b.height)/2,width:(a.width+b.width)/2,cx:(a.cx+b.cx)/2,bottom:(a.bottom+b.bottom)/2};
  const poses=Array.from({length:frames},(_,index)=>{const frame=isolate(extract(sheet,index,cell));return{frame,box:bounds(frame)};});
  const n0=poses[0].box,n1=poses.at(-1).box,neutral={height:(n0.height+n1.height)/2,width:(n0.width+n1.width)/2,cx:(n0.cx+n1.cx)/2,bottom:(n0.bottom+n1.bottom)/2};
  const desired=Math.sqrt(target.height/neutral.height*target.width/neutral.width);
  let scale=desired;
  for(let index=1;index<frames-1;index++){
    const box=poses[index].box,lift=action==='play'&&index>6&&index<19?Math.sin((index-6)/13*Math.PI)*34/desired:0;
    scale=Math.min(scale,(target.cx-6)/Math.max(1,neutral.cx-box.left),(size-6-target.cx)/Math.max(1,box.right-neutral.cx),(target.bottom-6)/Math.max(1,box.bottom-box.top+lift));
  }
  const ratio=scale/desired,output=canvas(columns*packedSize,4*packedSize),ctx=output.getContext('2d');
  const wavePaths={
    'cream-cat':[[.36,.7],[.24,.47],.16],shiba:[[.32,.85],[.27,.47],.15],
    'lop-rabbit':[[.39,.67],[.33,.48],.14],'little-fox':[[.32,.85],[.26,.46],.15],
  };
  for(let index=0;index<frames;index++){
    const frame=canvas(),fc=frame.getContext('2d');
    if(index===0||index===frames-1){fc.translate(target.cx,target.bottom);fc.scale(ratio,ratio);fc.translate(-target.cx,-target.bottom);fc.drawImage(index===0?first:last,0,0);}
    else{
      const {frame:pose,box}=poses[index],lift=action==='play'&&index>6&&index<19?Math.sin((index-6)/13*Math.PI)*34*ratio:0;
      fc.drawImage(pose,target.cx-neutral.cx*scale,target.bottom-box.bottom*scale-lift,cell*scale,cell*scale);
    }
    if(action==='wave'&&index>0&&index<frames-1){
      // Lock the resting body/face texture; the new artwork supplies the moving foreleg.
      const stable=canvas(),sc=stable.getContext('2d');sc.translate(target.cx,target.bottom);sc.scale(ratio,ratio);sc.translate(-target.cx,-target.bottom);sc.drawImage(first,0,0);
      const base=sc.getImageData(0,0,size,size),moving=fc.getImageData(0,0,size,size),[[ax,ay],[bx,by],radius]=wavePaths[id];
      for(let y=0;y<size;y++)for(let x=0;x<size;x++){
        const px=x/size,py=y/size,t=Math.max(0,Math.min(1,((px-ax)*(bx-ax)+(py-ay)*(by-ay))/((bx-ax)**2+(by-ay)**2)));
        const distance=Math.hypot(px-ax-t*(bx-ax),py-ay-t*(by-ay));
        const w=Math.max(0,Math.min(1,(radius-distance)/.025)),p=(y*size+x)*4,a0=base.data[p+3]*(1-w),a1=moving.data[p+3]*w,total=a0+a1;
        for(let c=0;c<3;c++)moving.data[p+c]=total?(base.data[p+c]*a0+moving.data[p+c]*a1)/total:0;
        moving.data[p+3]=total;
      }
      fc.putImageData(moving,0,0);
    }
    const check=bounds(frame);if(check.left<1||check.top<1||check.right>size-2||check.bottom>size-2)throw new Error(`${id}/${action}/${index} touches the cell edge`);
    ctx.drawImage(frame,index%columns*packedSize,Math.floor(index/columns)*packedSize,packedSize,packedSize);
  }
  const bytes=await output.encode('webp',90);await writeFile(asset(id,action),bytes);
  console.log(JSON.stringify({id,action,poses:frames,bytes:bytes.length,scale,ratio}));
}
