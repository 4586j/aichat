import { test, expect } from '@playwright/test';

const createPersona = async (request, name) => (await (await request.post('/api/personas', { data: { name, systemPrompt: '离线图谱验证助手' } })).json()).persona.id;
const triple = (subject, predicate, object) => ({ subject: { name: subject, type: 'topic' }, predicate, object: { name: object, type: 'topic' } });
const createMemory = async (request, personaId, content, triples) => (await (await request.post('/api/memories', { data: { personaId, content, ...(triples === undefined ? {} : { triples }) } })).json()).memory;
const openGraph = async (page, personaId) => {
  await page.goto('/#memories');
  await page.getByRole('button', { name: '知识图谱', exact: true }).click();
  await page.getByLabel('图谱所属角色', { exact: true }).selectOption(personaId);
  await expect(page.locator('#memory-graph-container canvas').first()).toBeVisible();
};

test('graph manual relations persist, expose evidence and follow archival lifecycle', async ({ page, request }, testInfo) => {
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('console', message => { if (message.type() === 'error') errors.push(message.text()); });
  const personaId = await createPersona(request, '图谱关系验证');
  await createMemory(request, personaId, '茉莉茶属于花茶。', [triple('茉莉茶', '属于', '花茶')]);
  await createMemory(request, personaId, '花茶适合午后休息。', [triple('花茶', '适合', '午后休息')]);
  await page.goto('/#memories');
  await page.getByRole('button', { name: '添加记忆', exact: true }).click();
  await page.locator('#memory-personaId').selectOption(personaId);
  await page.getByLabel('记忆内容', { exact: true }).fill('用户喜欢在午后喝茉莉茶。');
  await page.getByLabel('图谱关系（可选）', { exact: true }).fill('用户 | 喜欢 | 茉莉茶');
  await page.getByRole('dialog').getByRole('button', { name: '添加记忆', exact: true }).click();
  await expect(page.getByRole('dialog')).not.toBeVisible();
  const data = await (await request.get('/api/bootstrap')).json();
  const memory = data.memories.find(row => row.personaId === personaId && row.content.startsWith('用户喜欢'));
  expect(memory.triples[0].predicate).toBe('喜欢');
  expect(memory.graphIndexed).toBe(true);
  await page.locator('#memory-role').selectOption(personaId);
  await page.getByRole('button', { name: '知识图谱', exact: true }).click();
  await expect(page.locator('#memory-graph-container canvas').first()).toBeVisible();
  await expect(page.getByRole('button', { name: '提取待处理关系', exact: true })).toBeDisabled();
  await expect(page.locator('[data-stat="relationCount"]')).toHaveText('3');
  await page.getByTestId('memory-graph-edge').filter({ hasText: '用户 — 喜欢 → 茉莉茶' }).click();
  await expect(page.getByTestId('memory-graph-details')).toContainText(memory.content);
  await expect(page.getByTestId('memory-graph-original-text')).toHaveText(memory.content);
  await page.getByTestId('memory-graph-open-memory').click();
  await expect(page.getByLabel('记忆内容', { exact: true })).toHaveValue(memory.content);
  await page.getByRole('button', { name: '取消', exact: true }).click();
  const zoom = page.getByTestId('memory-graph-zoom');
  const beforeZoom = await zoom.textContent();
  await page.getByRole('button', { name: '放大图谱', exact: true }).click();
  await expect(zoom).not.toHaveText(beforeZoom);
  await page.getByRole('button', { name: '适配视图', exact: true }).click();
  await page.getByTestId('memory-graph-evidence-toggle').uncheck();
  await expect(page.getByTestId('memory-graph-edge')).toHaveCount(3);
  await page.getByTestId('memory-graph-search').fill('zzzz不存在的实体');
  await page.getByTestId('memory-graph-filter').check();
  await expect(page.getByTestId('memory-graph-empty')).toContainText('没有匹配');
  await page.getByRole('button', { name: '清除搜索', exact: true }).click();
  await page.getByTestId('memory-graph-filter').uncheck();
  await page.getByTestId('memory-graph-search').fill('茉莉茶');
  await page.getByRole('button', { name: '聚焦结果', exact: true }).click();
  await expect(page.getByTestId('memory-graph-node-list')).toContainText('茉莉茶');
  await page.getByRole('button', { name: '清除搜索', exact: true }).click();
  await page.getByTestId('memory-graph-evidence-toggle').check();
  await page.getByRole('button', { name: '重新布局', exact: true }).click();
  const canvas = page.getByTestId('memory-graph-canvas');
  await canvas.scrollIntoViewIfNeeded();
  const node = await canvas.evaluate(element => {
    const item = element._cyreg.cy.nodes().filter(n => n.data('kind') === 'entity' && n.data('caption') === '茉莉茶').first();
    return { id: item.id(), rendered: item.renderedPosition(), position: item.position() };
  });
  const bounds = await canvas.boundingBox();
  await page.mouse.move(bounds.x + node.rendered.x, bounds.y + node.rendered.y);
  await page.mouse.down();
  await page.mouse.move(bounds.x + node.rendered.x + 35, bounds.y + node.rendered.y + 25, { steps: 8 });
  await page.mouse.up();
  const moved = await canvas.evaluate((element, id) => element._cyreg.cy.getElementById(id).position(), node.id);
  expect(Math.hypot(moved.x - node.position.x, moved.y - node.position.y)).toBeGreaterThan(5);
  await page.getByTestId('memory-graph-stage').focus();
  const pan = await canvas.evaluate(element => element._cyreg.cy.pan().x);
  await page.keyboard.press('ArrowRight');
  expect(await canvas.evaluate(element => element._cyreg.cy.pan().x)).not.toBe(pan);
  await page.getByTestId('memory-graph-node').filter({ hasText: '茉莉茶' }).filter({ has: page.locator('.mg-kind-entity') }).click();
  while (await page.getByRole('button', { name: '关闭通知', exact: true }).count()) await page.getByRole('button', { name: '关闭通知', exact: true }).first().click();
  await page.getByRole('button', { name: '知识图谱', exact: true }).focus();
  await page.evaluate(() => window.scrollTo({ top: 0, behavior: 'instant' }));
  await page.screenshot({ path: testInfo.outputPath('desktop-memory-graph.png'), fullPage: true });
  await page.getByTestId('memory-graph').screenshot({ path: testInfo.outputPath('desktop-graph-detail.png') });

  await page.getByRole('button', { name: '记忆列表', exact: true }).click();
  const card = page.locator('.memory-card').filter({ hasText: memory.content });
  await card.getByRole('button', { name: '归档', exact: true }).click();
  await expect(card).toHaveCount(0);
  await page.getByRole('button', { name: '知识图谱', exact: true }).click();
  await expect(page.locator('#memory-graph-container canvas').first()).toBeVisible();
  let graph = await (await request.get(`/api/graph?personaId=${personaId}`)).json();
  expect(graph.edges.filter(edge => edge.kind === 'relation')).toHaveLength(2);
  await page.getByLabel('包含归档记忆', { exact: true }).check();
  await expect(page.locator('#memory-graph-container canvas').first()).toBeVisible();
  graph = await (await request.get(`/api/graph?personaId=${personaId}&includeArchived=true`)).json();
  expect(graph.nodes.find(node => node.memoryId === memory.id).status).toBe('archived');
  await page.getByRole('button', { name: '记忆列表', exact: true }).click();
  await page.getByLabel('记忆状态', { exact: true }).selectOption('archived');
  await card.getByRole('button', { name: '恢复', exact: true }).click();
  await page.getByLabel('记忆状态', { exact: true }).selectOption('active');
  await card.getByRole('button', { name: '编辑', exact: true }).click();
  await expect(page.getByLabel('图谱关系（可选）', { exact: true })).toHaveValue('用户 | 喜欢 | 茉莉茶');
  await page.getByLabel('图谱关系（可选）', { exact: true }).fill('无效关系');
  await page.getByRole('button', { name: '保存记忆', exact: true }).click();
  await expect(page.locator('#dialog-error')).toContainText('主体 | 关系 | 客体');
  await page.getByRole('button', { name: '取消', exact: true }).click();
  expect(errors).toEqual([]);
});

test('graph extraction is explicit, isolated, handles errors and retains pending memories', async ({ page, request }) => {
  const personaId = await createPersona(request, '关系提取验证');
  const otherId = await createPersona(request, '图谱隔离验证');
  const memory = await createMemory(request, personaId, '用户喜欢茉莉茶。');
  await createMemory(request, otherId, '其他角色喜欢茉莉茶。');
  const requests = [];
  page.on('request', r => { if (r.url().endsWith('/api/graph/extract')) requests.push(r.url()); });
  await openGraph(page, personaId);
  expect(requests).toHaveLength(0);
  await page.getByRole('button', { name: '提取待处理关系', exact: true }).click();
  await expect(page.getByRole('dialog')).toContainText('发送至你配置的模型服务');
  await page.getByRole('button', { name: '取消', exact: true }).click();
  expect(requests).toHaveLength(0);
  await request.put('/api/settings', { data: { model: '' } });
  try {
    await page.getByRole('button', { name: '提取待处理关系', exact: true }).click();
    await page.getByRole('button', { name: '确认并提取关系', exact: true }).click();
    await expect(page.locator('#dialog-error')).toContainText('模型名称');
    await page.getByRole('button', { name: '取消', exact: true }).click();
  } finally { await request.put('/api/settings', { data: { model: 'offline-ui-test' } }); }
  await page.getByRole('button', { name: '提取待处理关系', exact: true }).click();
  await page.getByRole('button', { name: '确认并提取关系', exact: true }).click();
  await expect(page.getByRole('dialog')).not.toBeVisible();
  await expect(page.getByRole('button', { name: '提取待处理关系', exact: true })).toBeDisabled();
  const graph = await (await request.get(`/api/graph?personaId=${personaId}`)).json();
  expect(graph.stats.relationCount).toBe(1);
  expect(graph.nodes.find(node => node.memoryId === memory.id).indexed).toBe(true);
  await page.getByLabel('图谱所属角色', { exact: true }).selectOption(otherId);
  await expect(page.getByRole('button', { name: '提取待处理关系', exact: true })).toBeEnabled();
  const other = await (await request.get(`/api/graph?personaId=${otherId}`)).json();
  expect(other.stats.relationCount).toBe(0);
  expect(other.stats.pendingCount).toBe(1);
});

test('mobile graph, empty graph and failed graph reads remain usable', async ({ page, request }, testInfo) => {
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  const personaId = await createPersona(request, '手机图谱验证');
  const emptyId = await createPersona(request, '空图谱验证');
  await createMemory(request, personaId, '用户喜欢茉莉茶，茉莉茶属于花茶。', [triple('用户', '喜欢', '茉莉茶'), triple('茉莉茶', '属于', '花茶')]);
  await page.setViewportSize({ width: 390, height: 844 });
  await openGraph(page, personaId);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: testInfo.outputPath('mobile-memory-graph.png'), fullPage: true });
  await page.getByLabel('图谱所属角色', { exact: true }).selectOption(emptyId);
  await expect(page.getByRole('button', { name: '提取待处理关系', exact: true })).toBeDisabled();
  await expect(page.locator('#memory-graph-container')).not.toBeEmpty();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.route('**/api/graph?**', route => route.fulfill({ status: 500, contentType: 'application/json', body: JSON.stringify({ error: '离线测试：读取失败' }) }));
  await page.getByRole('button', { name: '刷新图谱', exact: true }).click();
  await expect(page.getByRole('alert').filter({ hasText: '离线测试：读取失败' })).toBeVisible();
  await page.unroute('**/api/graph?**');
  await page.getByRole('button', { name: '刷新图谱', exact: true }).click();
  await expect(page.locator('#main .inline-error')).toHaveCount(0);
  await page.getByRole('button', { name: '记忆列表', exact: true }).click();
  await expect(page.getByLabel('记忆状态', { exact: true })).toBeVisible();
  expect(errors).toEqual([]);
});
